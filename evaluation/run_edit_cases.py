"""Run a fixed set of image-editing cases through original and quantized pipelines.

Each case edits one image generated by the original model (re-style, remove,
change, or add), with a fixed seed so variants are directly comparable. Outputs
land in ``<output-root>/<variant>/<case_id>.png``.

Usage:
    python -m evaluation.run_edit_cases [--variants original datafree ...] \
        [--source-root outputs/eval/flux2-klein-9b/realistic-original/samples/realistic-32] \
        [--output-root outputs/eval/flux2-klein-9b/edits] [--steps 4]
"""

