def _enable_cross_device_generator() -> None:
    """Let diffusers draw noise from a generator on a different device.

    ``randn_tensor`` only supports a cpu generator with a non-cpu target, so a
    cuda generator with ``--device cpu`` raises. Rebind every module-level
    reference to a wrapper that samples on the generator's device and moves the
    result, keeping the noise identical to same-seed GPU runs.
    """

    import diffusers.utils.torch_utils as torch_utils

    original = torch_utils.randn_tensor

    def randn_tensor(shape, generator=None, device=None, dtype=None, layout=None):
        gen = generator[0] if isinstance(generator, list) and generator else generator
        if (
            isinstance(gen, torch.Generator)
            and device is not None
            and gen.device.type != "cpu"
            and torch.device(device).type != gen.device.type
        ):
            noise = original(shape, generator=generator, device=gen.device, dtype=dtype, layout=layout)
            return noise.to(device)
        return original(shape, generator=generator, device=device, dtype=dtype, layout=layout)

    for module in list(sys.modules.values()):
        try:
            # Lazy modules (e.g. transformers) may import optional deps on getattr.
            if module is not None and getattr(module, "randn_tensor", None) is original:
                module.randn_tensor = randn_tensor
        except Exception:
            continue

