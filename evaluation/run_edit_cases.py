@dataclass(frozen=True)
class EditCase:
    case_id: str
    category: str
    source: str  # filename inside --source-root
    instruction: str


CASES = [
    EditCase("restyle-watercolor", "restyle", "0005-0.png", "turn this into a watercolor painting"),
    EditCase("restyle-ukiyoe", "restyle", "0018-0.png", "make it look like a ukiyo-e woodblock print"),
    EditCase("restyle-sketch", "restyle", "0031-0.png", "convert this photo to a pencil sketch"),
    EditCase("remove-bicycle", "remove", "0008-0.png", "remove the bicycle"),
    EditCase("remove-car", "remove", "0006-0.png", "remove the car from the road"),
    EditCase("remove-balloons", "remove", "0027-0.png", "remove the balloons"),
    EditCase("change-car-color", "change", "0006-0.png", "change the blue car to a red car"),
    EditCase("change-armchair", "change", "0016-0.png", "change the yellow armchair to a dark green armchair"),
    EditCase("change-cat-rooster", "change", "0010-0.png", "replace the cat with a white rooster"),
    EditCase("add-juice", "add", "0013-0.png", "add a glass of orange juice to the table"),
    EditCase("add-sailboat", "add", "0004-0.png", "add a small sailboat on the waves"),
    EditCase("add-hiker", "add", "0020-0.png", "add a second hiker in a blue jacket next to the first one"),
]


def _seed_for(case: EditCase) -> int:
    return sum(ord(c) for c in case.case_id) * 9973 % (2**31)


def run_variant(
    variant: str,
    *,
    source_root: Path,
    output_root: Path,
    steps: int,
    device: str,
    offload: str,
    generator_device: str | None = None,
) -> None:
    checkpoint = CHECKPOINTS.get(variant)
    spec = RuntimePipelineSpec(
        mode="original" if checkpoint is None else "quantized",
        runtime="none" if checkpoint is None else "torch-dequant",
        checkpoint=checkpoint,
        precision=PRECISIONS.get(variant, "fp4"),
        device=device,
        torch_dtype="bfloat16",
        torch_dequant_activation_mode="input",
        pipeline_offload=offload,
    )
    pipe = load_evaluation_pipeline(model_id=MODEL_ID, spec=spec)
    if generator_device is not None and torch.device(generator_device).type != torch.device(device).type:
        _enable_cross_device_generator()
    out_dir = output_root / variant
    out_dir.mkdir(parents=True, exist_ok=True)
    with torch.inference_mode():
        for case in CASES:
            out_path = out_dir / f"{case.case_id}.png"
            if out_path.exists():
                print(f"[{variant}] {case.case_id}: exists, skipping", flush=True)
                continue
            source = Image.open(source_root / case.source).convert("RGB")
            generator = torch.Generator(generator_device or device).manual_seed(_seed_for(case))
            result = pipe(
                image=[source],
                prompt=[case.instruction],
                num_inference_steps=steps,
                guidance_scale=1.0,
                generator=generator,
            )
            result.images[0].save(out_path)
            print(f"[{variant}] {case.case_id}: saved", flush=True)
    del pipe
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--variants", nargs="+", default=["original", *CHECKPOINTS], choices=["original", *CHECKPOINTS]
    )
    parser.add_argument(
        "--source-root",
        default="outputs/eval/flux2-klein-9b/realistic-original/samples/realistic-32",
    )
    parser.add_argument("--output-root", default="outputs/eval/flux2-klein-9b/edits")
    parser.add_argument("--steps", type=int, default=4)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument(
        "--generator-device",
        default=None,
        help="Device for the RNG (defaults to --device). Use cuda with --device cpu to keep "
        "noise identical to GPU runs while computing on CPU.",
    )
    parser.add_argument("--pipeline-offload", default="model", choices=("none", "model", "sequential"))
    parser.add_argument("--cases", nargs="+", default=None, help="Restrict to these case ids.")
    args = parser.parse_args()

    global CASES
    if args.cases:
        by_id = {case.case_id: case for case in CASES}
        CASES = [by_id[case_id] for case_id in args.cases]
    source_root = Path(args.source_root)
    missing = [case.source for case in CASES if not (source_root / case.source).exists()]
    if missing:
        raise FileNotFoundError(f"Missing source images under {source_root}: {sorted(set(missing))}")
    for variant in args.variants:
        run_variant(
            variant,
            source_root=source_root,
            output_root=Path(args.output_root),
            steps=args.steps,
            device=args.device,
            offload=args.pipeline_offload,
            generator_device=args.generator_device,
        )


if __name__ == "__main__":
    main()
